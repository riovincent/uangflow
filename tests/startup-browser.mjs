import assert from 'node:assert/strict';
import {blank} from '../public/domain.js';
import {mkdir} from 'node:fs/promises';
const {chromium}=await import(process.env.UANGFLOW_PLAYWRIGHT_PATH||'@playwright/test');
const browser=await chromium.launch({channel:'msedge',headless:true});
const base=process.env.UANGFLOW_BASE_URL||'http://127.0.0.1:5193';
await mkdir('outputs/experience',{recursive:true});
try{
 const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
 await page.addInitScript(()=>localStorage.setItem('uangflow.language','id'));
 page.on('pageerror',e=>errors.push(e.message));
 let releaseConfig,releaseState;
 const configGate=new Promise(resolve=>releaseConfig=resolve),stateGate=new Promise(resolve=>releaseState=resolve);
 await page.route('**/api/auth-config',async route=>{await configGate;await route.fulfill({json:null});});
 await page.route('**/api/state',async route=>{await stateGate;await route.fulfill({json:{user:null,state:blank(),revision:0}});});
 const response=await page.goto(base,{waitUntil:'domcontentloaded'});
 const html=await response.text();
 assert.doesNotMatch(html,/Menyiapkan UangFlow|Memuat catatanmu|Menyiapkan ruang keuanganmu|loading-skeleton/);
 await page.locator('.opening').waitFor({state:'visible'});
 const opening=await page.locator('.opening').elementHandle(),hero=await page.locator('.hero').elementHandle();
 await page.waitForTimeout(900);
 await page.screenshot({path:'outputs/experience/startup-logo.png'});
 releaseConfig();await page.waitForRequest('**/api/state');
 releaseState();await page.waitForFunction(()=>document.querySelector('#app').getAttribute('aria-busy')===null);
 assert.ok(await opening.evaluate(node=>node.isConnected),'The same opening continues after data arrives');
 assert.ok(await hero.evaluate(node=>node.isConnected),'First render keeps the scene and animation intact');
 await page.locator('.opening').waitFor({state:'hidden'});
 await page.screenshot({path:'outputs/experience/startup-complete.png'});
 assert.equal(await page.locator('.loading,.loading-skeleton').count(),0);
 await page.close();
 const slow=await browser.newPage({reducedMotion:'reduce'});await slow.addInitScript(()=>localStorage.setItem('uangflow.language','id'));
 let releaseSlow;const slowGate=new Promise(resolve=>releaseSlow=resolve);
 await slow.route('**/api/auth-config',route=>route.fulfill({json:null}));
 await slow.route('**/api/state',async route=>{await slowGate;await route.fulfill({json:{user:null,state:blank(),revision:0}});});
 const slowRequest=slow.waitForRequest('**/api/state');await slow.goto(base);await slowRequest;
 await slow.getByRole('button',{name:'Jelajahi demo',exact:true}).click();
 await slow.waitForFunction(()=>location.hash==='#dashboard');
 releaseSlow();await slow.waitForFunction(()=>document.querySelector('#app').getAttribute('aria-busy')===null);
 assert.equal(new URL(slow.url()).hash,'#dashboard','Late account request must not replace a selected demo');
 assert.ok(await slow.getByText('Mode demo',{exact:true}).filter({visible:true}).isVisible());
 assert.equal(await slow.locator('.opening').count(),0,'Reduced motion skips opening');
 await slow.close();
 const failed=await browser.newPage({reducedMotion:'reduce'});await failed.addInitScript(()=>localStorage.setItem('uangflow.language','id'));
 await failed.route('**/api/auth-config',route=>route.fulfill({json:null}));
 await failed.route('**/api/state',route=>route.fulfill({status:503,json:{error:'Test koneksi'}}));
 await failed.goto(base);await failed.getByRole('heading',{name:'Catatan belum bisa dimuat.'}).waitFor();
 assert.ok(await failed.getByRole('button',{name:'Coba lagi',exact:true}).isVisible());
 assert.equal(await failed.locator('.opening,.loading-skeleton').count(),0);
 assert.deepEqual(errors,[]);
 console.log('PASS: opening starts before delayed account requests, no loading text/skeleton, no restart on data arrival, late data preserves demo, reduced motion, and recoverable fetch errors.');
}finally{await browser.close();}
